const RULES = [
  [/餐|飲|食|吃|早午|晚餐|午餐/, "🍱"], [/日常|用品|生活|超市|雜貨/, "🧴"], [/交通|油|車|捷運|公車|計程/, "🚌"],
  [/水電|電費|水費|瓦斯|居家/, "💡"], [/房貸利息|利息支出/, "🏦"], [/房租|房貸|租屋|管理費/, "🏠"], [/通訊|網路|手機|電話/, "📱"],
  [/醫療|保健|看病|藥/, "🩺"], [/健保/, "🏥"], [/保險|保費/, "🛡️"], [/服飾|美容|衣|美髮/, "👗"], [/娛樂|休閒|電影/, "🎬"],
  [/旅遊|旅行|出國/, "✈️"], [/教育|學習|書|課/, "📚"], [/人情|交際|禮/, "🎁"], [/孝親|家用|家人|孫/, "👪"],
  [/稅|規費|罰/, "🧾"], [/捐|公益/, "💗"], [/寵物/, "🐾"], [/運動|健身/, "🏃"],
  [/薪資|薪水|工資/, "💼"], [/退休|年金/, "🌿"], [/股利|股息/, "📈"], [/利息/, "💰"], [/租金/, "🏘️"],
  [/獎金|獎/, "🏅"], [/紅包/, "🧧"], [/退款|退費/, "↩️"],
];

export function catEmoji(name, kind) {
  for (const [re, e] of RULES) if (re.test(name || "")) return e;
  return kind === "income" ? "💵" : kind === "expense" ? "🏷️" : "";
}
